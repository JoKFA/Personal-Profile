// open one entry and screenshot the window, the body, the end: node p3b-one.mjs <out> <id> [WxH] [base]
import { launch, until } from './lib.mjs'
const [OUT, ID = 'X-001', SIZE = '390x664', BASE = 'http://127.0.0.1:5194'] = process.argv.slice(2)
const [W, H] = SIZE.split('x').map(Number)
const { b, p, errs } = await launch(W, H)
await p.goto(`${BASE}/?phone-app&phone-expose`, { waitUntil: 'load' })
await until(p, () => window.__phone && window.__phone.ready)
await p.waitForTimeout(1200)
await p.touchscreen.tap(W / 2, H * 0.4)
await p.evaluate((id) => window.__phone.openEntry(id), ID)
await p.waitForTimeout(1300); await p.screenshot({ path: `${OUT}/${ID}-a-opening.png` })
await until(p, () => window.__phone.phase === 'file'); await p.waitForTimeout(900)
await p.screenshot({ path: `${OUT}/${ID}-b-window.png` })
const info = await p.evaluate(() => { const f = document.querySelector('.ph-file'); return { sh: f.scrollHeight, ch: f.clientHeight, wz: getComputedStyle(f).getPropertyValue('--ph-wz') } })
console.log(JSON.stringify(info))
await p.evaluate(() => { scrollTo(0, document.documentElement.scrollHeight) })
await p.waitForTimeout(1500)
await p.screenshot({ path: `${OUT}/${ID}-c-end.png` })
console.log(errs)
await b.close()
